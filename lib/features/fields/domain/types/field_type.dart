/// Тип поля.
///
/// Определяет, какой компонент редактора будет использоваться,
/// как поле сортируется, фильтруется и хранится.
enum FieldType {
  /// Обычный текст.
  text,

  /// Целое число.
  integer,

  /// Дробное число.
  decimal,

  /// Дата.
  date,

  /// Логическое значение.
  boolean,

  /// Значение из справочника.
  dictionary,

  /// Ссылка на другую сущность.
  reference,

  /// Изображение.
  image,

  /// Файл.
  attachment,

  /// Рейтинг.
  rating,
}